def area(a):
    """Рассчитывает площадь квадрата.

    Площадь равна квадрату длины стороны: S = a * a.

    Args:
        a: длина стороны квадрата (число, больше нуля).

    Returns:
        Площадь квадрата.

    Example:
        >>> square.area(8)
        64
    """
    return a * a


def perimeter(a):
    """Рассчитывает периметр квадрата.

    Периметр равен сумме длин всех четырёх сторон: P = 4 * a.

    Args:
        a: длина стороны квадрата (число, больше нуля).

    Returns:
        Периметр квадрата.

    Example:
        >>> square.perimeter(8)
        32
    """
    return 4 * a
