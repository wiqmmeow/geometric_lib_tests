def area(a, h):
    """Рассчитывает площадь треугольника.

    Площадь равна половине произведения основания на проведённую к нему
    высоту: S = a * h / 2.

    Args:
        a: длина основания (число, больше нуля).
        h: высота, опущенная на это основание (число, больше нуля).

    Returns:
        Площадь треугольника.

    Example:
        >>> triangle.area(5, 2)
        5.0
    """
    return a * h / 2


def perimeter(a, b, c):
    """Рассчитывает периметр треугольника.

    Периметр равен сумме длин трёх сторон: P = a + b + c.

    Args:
        a: длина первой стороны (число, больше нуля).
        b: длина второй стороны (число, больше нуля).
        c: длина третьей стороны (число, больше нуля).

    Returns:
        Периметр треугольника.

    Example:
        >>> triangle.perimeter(3, 3, 5)
        11
    """
    return a + b + c 
