def area(a, b):
    """Рассчитывает площадь прямоугольника.

    Площадь равна произведению двух смежных сторон: S = a * b.

    Args:
        a: длина одной стороны (число, больше нуля).
        b: длина смежной стороны (число, больше нуля).

    Returns:
        Площадь прямоугольника.

    Example:
        >>> rectangle.area(4, 9)
        36
    """
    return a * b


def perimeter(a, b):
    """Рассчитывает периметр прямоугольника.

    Противоположные стороны равны, поэтому P = 2 * (a + b).

    Args:
        a: длина одной стороны (число, больше нуля).
        b: длина смежной стороны (число, больше нуля).

    Returns:
        Периметр прямоугольника.

    Example:
        >>> rectangle.perimeter(4, 9)
        26
    """
    return 2 * (a + b)